¿Que es crud?
CRUD es un acrónimo en inglés que significa Create (Crear), Read (Leer), Update (Actualizar) y Delete (Borrar). Representa las cuatro operaciones básicas necesarias para gestionar datos de forma persistente en bases de datos, aplicaciones y sistemas informáticos

Create :Esta es una de las funciones mas importantes del CRUD, ya que a travez de ella, podemos crear tablas y crear bases de datos ademas de subir datos las mismas, en HTML es Post y en MySQL es Insert.
